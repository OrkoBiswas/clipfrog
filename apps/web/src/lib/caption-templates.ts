export type CaptionTemplate = {
  id: string;
  name: string;
  category: string;
  description: string;
  accent: string;
  sample: string;
  config: CaptionStyle;
};
function preset(
  id: string,
  name: string,
  category: string,
  description: string,
  accent: string,
  sample: string,
  animation: CaptionAnimation,
  config: CaptionStyle,
): CaptionTemplate {
  return {
    id,
    name,
    category,
    description,
    accent,
    sample,
    config: {
      ...DEFAULT_CAPTION,
      font: "Urbanist",
      size: 72,
      outline: 3,
      lines: 1,
      max_words: 3,
      max_chars_per_line: 20,
      highlight: true,
      animation_duration: 0.24,
      animation,
      ...config,
      style: name,
    },
  };
}
