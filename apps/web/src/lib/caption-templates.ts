/** Apply appearance without changing an existing clip's transcript. */
export function applyCaptionTemplate(
  current: CaptionStyle,
  config: CaptionStyle,
): CaptionStyle {
  return { ...config, enabled: current.enabled ?? true, cues: current.cues };
}
